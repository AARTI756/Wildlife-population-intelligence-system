def normalize_class_name(raw_name: str) -> str:
    """Normalize and alias-map any YOLO raw class name to lookup keys."""
    if not raw_name:
        return ""
    
    # 1. Clean spacing and casings
    cleaned = raw_name.strip().lower().replace("_", " ").replace("-", " ")
    
    # 2. Manual mappings for specific alias exceptions
    if cleaned in ["wild boar", "wildboar", "wild-boar"]:
        return "wild boar"
    if cleaned in ["brown bear", "brownbear", "brown-bear"]:
        return "brown-bear"
    if cleaned in ["polar bear", "polarbear", "polar-bear"]:
        return "polar-bear"
    if cleaned in ["red panda", "redpanda", "red-panda"]:
        return "red-panda"
    if cleaned in ["moths and butterflies", "moths-and-butterflies", "moth and butterfly", "moth"]:
        return "moths-and-butterflies"
        
    return cleaned


def lookup_taxonomy_profile(raw_name: str) -> dict | None:
    """Deterministic lookup of taxonomy profiles for the 64 YOLO classes."""
    norm = normalize_class_name(raw_name)
    if not norm:
        return None
        
    # Strict O(1) dictionary key lookup
    profile = TAXONOMY_DATABASE.get(norm)
    if profile:
        return dict(profile)
        
    return None
